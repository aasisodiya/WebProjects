// Builds showcase/notes.js from every README.md under Notes/ (plus the animations notes).
// Re-run after adding or editing notes:  node showcase/tools/build-notes.mjs
//
// Each note gets its title (# heading), topics (## headings with GitHub-style anchors),
// a category and the dates it was first added / last changed in git.

import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, dirname, resolve, relative } from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");

// Index pages that only link to other notes.
const SKIP = new Set(["Notes/README.md", "Notes/note-js-jquery/README.md"]);
const EXTRA = ["26Animations/README.md"];

const CATEGORY_RULES = [
  [/note-(aframe|threejs|webxr)/, "3d"],
  [/note-(html|open-graph|imports)/, "html"],
  [/note-(js-jquery|intersection-observer|canvas)/, "js"],
  [/./, "css"],
];

function findReadmes(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return findReadmes(full);
    return name === "README.md" ? [relative(ROOT, full).replace(/\\/g, "/")] : [];
  });
}

// Titles that would otherwise collide with another note's.
const TITLE_OVERRIDES = { "Notes/note-css-2/": "CSS Notes II" };

const plain = (md) => md.replace(/\[([^\]]*)\]\([^)]*\)/g, "$1").trim();

function githubSlug(text, seen) {
  let s = text
    .replace(/`/g, "")
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, "")
    .replace(/\s/g, "-");
  const n = seen.get(s) || 0;
  seen.set(s, n + 1);
  return n ? `${s}-${n}` : s;
}

function gitDate(file, first) {
  const out = execFileSync("git", ["log", "--follow", "--format=%as", "--", file], { cwd: ROOT, encoding: "utf8" })
    .trim()
    .split("\n");
  return first ? out[out.length - 1] : out[0];
}

const notes = [...findReadmes(join(ROOT, "Notes")), ...EXTRA]
  .filter((f) => !SKIP.has(f))
  .map((file) => {
    const lines = readFileSync(join(ROOT, file), "utf8").split(/\r?\n/);
    const seen = new Map();
    let title = "";
    let summary = "";
    const topics = [];
    let inCode = false;
    for (const line of lines) {
      if (/^\s*```/.test(line)) inCode = !inCode;
      if (inCode) continue;
      const h = line.match(/^(#{1,2})\s+(.+?)\s*#*$/);
      if (h && h[1] === "#" && !title) {
        title = plain(h[2]);
        githubSlug(h[2], seen);
      } else if (h && h[1] === "##") {
        const text = plain(h[2]);
        if (/^(reference|references|todo)$/i.test(text.replace(/`/g, ""))) continue;
        topics.push({ t: text, a: githubSlug(text, seen) });
      } else if (title && !summary && !topics.length && /^[A-Za-z`]/.test(line) && !/^(#|>|\||-|\*|!)/.test(line)) {
        summary = plain(line).slice(0, 180);
      } else if (/^#{3,}\s/.test(line)) {
        githubSlug(line.replace(/^#+\s+/, ""), seen);
      }
    }
    const path = dirname(file) + "/";
    return {
      t: TITLE_OVERRIDES[path] || title,
      p: path,
      c: CATEGORY_RULES.find(([re]) => re.test(path))[1],
      d: gitDate(file, true),
      u: gitDate(file, false),
      s: summary,
      topics,
    };
  })
  .sort((a, b) => b.topics.length - a.topics.length);

writeFileSync(
  join(ROOT, "showcase/notes.js"),
  "// Generated by showcase/tools/build-notes.mjs — do not edit by hand.\n" +
    "window.SHOWCASE_NOTES = " +
    JSON.stringify(notes, null, 1) +
    ";\n"
);
console.log(`Wrote ${notes.length} notes, ${notes.reduce((n, x) => n + x.topics.length, 0)} topics`);
